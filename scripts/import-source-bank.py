    structural=re.compile(r'^(ФИЗИЧЕСК|ПРИМЕРЫ|ЕДИНИЦ|ПРИБОР|ОПРЕДЕЛЕНИЯ|ТЕХНИЧЕСКИЕ|ДЕЙСТВИЯ|РАЗМЕРНОСТ|НАИМЕНОВАНИЕ|A\)|А\)|Б\)|B\)|В\)|\d+\))')
    for s in lines:
        if not s:
            if buf: result.append(buf.strip()); buf=''
            continue
        if structural.match(s):
            if buf: result.append(buf.strip()); buf=''
            result.append(s)
        else:
            if buf: buf += ' '+s
            else: buf=s
    if buf: result.append(buf.strip())
    # Remove isolated answer-table labels generated by PDF print layout.
    result=[x for x in result if x not in {'А','Б','В','A','B'}]
    cleaned=[]
    for x in result:
        if x.startswith('Запишите в ответ цифры'):
            x=re.sub(r'[:\s]+[AАБВB]+$', '', x).strip()
        cleaned.append(x)
    return '\n'.join(cleaned).strip()

