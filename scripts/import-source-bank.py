def extract_blocks(pdf):
    raw=subprocess.check_output(['pdftotext',pdf,'-']).decode('utf-8','ignore')
    matches=list(re.finditer(r'(?m)^\s*(\d+)\.\s+Тип\s+(\d+)\s+№\s+(\d+)\s+i\s*$',raw))
    out={}
    for n,m in enumerate(matches):
        end=matches[n+1].start() if n+1<len(matches) else len(raw)
        out[int(m.group(3))]=raw[m.end():end]
    return out

